#!/usr/bin/env sh
# Install px0-ide (px0 in its own Electron window) from this checkout.
#
# Usage:   ./install-ide.sh
# Result:  `px0-ide` in ~/.local/bin always opens the Electron app.
#          `px0-ide` opens the current directory; `px0-ide <dir|file|pr-url>` opens that target.
#          The regular `px0` command is left untouched.
#
# Environment variables:
#   INSTALL_DIR  - where the launcher goes (default: ~/.local/bin)
#   APP_DIR      - where the app and server binary live (default: ~/.local/share/px0-ide)

set -eu

ROOT="$(cd "$(dirname "$0")" && pwd)"
HERE="$ROOT/electron"
INSTALL_DIR="${INSTALL_DIR:-$HOME/.local/bin}"
APP_DIR="${APP_DIR:-$HOME/.local/share/px0-ide}"

step() { printf ' › %s\n' "$1"; }
fail() { printf ' ✗ %s\n' "$1" >&2; exit 1; }

command -v npm >/dev/null 2>&1 || fail "npm is required to install Electron"

# 1. Server binary
if command -v go >/dev/null 2>&1 && command -v node >/dev/null 2>&1; then
  step "Building px0 server..."
  (cd "$ROOT" && make build >/dev/null)
elif [ ! -x "$ROOT/px0" ]; then
  fail "No ./px0 binary and no Go/Node toolchain to build one (run 'make build' first)"
fi

# 2. App files
step "Installing app to $APP_DIR..."
mkdir -p "$APP_DIR" "$INSTALL_DIR"
rm -f "$APP_DIR/px0" # new inode: macOS kills a binary overwritten in place (exit 137)
cp "$ROOT/px0" "$APP_DIR/px0"
cp -R "$HERE/main.js" "$HERE/launch.js" "$HERE/package.json" "$HERE/package-lock.json" "$HERE/assets" "$HERE/scripts" "$APP_DIR/"
(cd "$APP_DIR" && npm install --no-audit --no-fund --loglevel=error)

# 3. Launcher: keeps the caller's cwd, so a bare `px0-ide` opens the current directory.
LAUNCHER="$INSTALL_DIR/px0-ide"
cat > "$LAUNCHER" <<LAUNCH
#!/usr/bin/env sh
# px0-ide launcher (generated by install-ide.sh)
exec node "$APP_DIR/launch.js" "\$@"
LAUNCH
chmod +x "$LAUNCHER"

printf ' ✓ Installed %s\n' "$LAUNCHER"
case ":$PATH:" in
  *":$INSTALL_DIR:"*) ;;
  *) printf ' ! %s is not on your PATH; add: export PATH="%s:$PATH"\n' "$INSTALL_DIR" "$INSTALL_DIR" ;;
esac
