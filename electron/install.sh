#!/usr/bin/env sh
# Install px0 app mode from this checkout.
#
# Usage:   ./electron/install.sh
# Result:  `px0` in ~/.local/bin opens a px0 window on the current directory.
#          `px0 <dir|file|pr-url>` opens that target instead.
#
# Environment variables:
#   INSTALL_DIR  - where the launcher goes (default: ~/.local/bin)
#   APP_DIR      - where the app and server binary live (default: ~/.local/share/px0-app)

set -eu

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(dirname "$HERE")"
INSTALL_DIR="${INSTALL_DIR:-$HOME/.local/bin}"
APP_DIR="${APP_DIR:-$HOME/.local/share/px0-app}"

step() { printf ' › %s\n' "$1"; }
fail() { printf ' ✗ %s\n' "$1" >&2; exit 1; }

command -v npm >/dev/null 2>&1 || fail "npm is required to install Electron"

# 1. Server binary
if command -v go >/dev/null 2>&1 && command -v node >/dev/null 2>&1; then
  step "Building px0 server..."
  (cd "$ROOT" && make build >/dev/null)
elif [ ! -x "$ROOT/px0" ]; then
  fail "No ./px0 binary and no Go/Node toolchain to build one (run 'make build' first)"
fi

# 2. App files
step "Installing app to $APP_DIR..."
mkdir -p "$APP_DIR" "$INSTALL_DIR"
cp "$ROOT/px0" "$APP_DIR/px0"
cp -R "$HERE/main.js" "$HERE/package.json" "$HERE/package-lock.json" "$HERE/assets" "$HERE/scripts" "$APP_DIR/"
(cd "$APP_DIR" && npm install --no-audit --no-fund --loglevel=error)

# 3. Launcher: keeps the caller's cwd, so a bare `px0` opens the current directory.
LAUNCHER="$INSTALL_DIR/px0"
if [ -e "$LAUNCHER" ] && ! grep -q 'px0-app launcher' "$LAUNCHER" 2>/dev/null; then
  printf ' ! Replacing existing %s (backup: %s.bak)\n' "$LAUNCHER" "$LAUNCHER"
  mv "$LAUNCHER" "$LAUNCHER.bak"
fi
cat > "$LAUNCHER" <<EOF
#!/usr/bin/env sh
# px0-app launcher (generated by electron/install.sh)
APP_DIR="$APP_DIR"
case "\${1:-}" in
  --version|-v|version|--update|--help|-h) PX0_BIN="\$APP_DIR/px0"; exec "\$PX0_BIN" "\$@" ;;
esac
export PX0_BIN="\$APP_DIR/px0"
LOG="\${TMPDIR:-/tmp}/px0-app.log"
nohup "\$APP_DIR/node_modules/.bin/electron" "\$APP_DIR" "\$@" >"\$LOG" 2>&1 &
EOF
chmod +x "$LAUNCHER"

printf ' ✓ Installed %s\n' "$LAUNCHER"
case ":$PATH:" in
  *":$INSTALL_DIR:"*) ;;
  *) printf ' ! %s is not on your PATH; add: export PATH="%s:$PATH"\n' "$INSTALL_DIR" "$INSTALL_DIR" ;;
esac
